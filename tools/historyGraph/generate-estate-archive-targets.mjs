import fs from "node:fs";
import path from "node:path";
import { colonialEstates } from "../../src/data/historyGraph/colonialEstates.ts";

const OUT_FILE = path.resolve(
  "src/data/historyGraph/extractionTargets/generatedEstateArchiveTargets.ts"
);

function archiveForEstate(estate) {
  if (estate.island === "st_john") return "Rigsarkivet";

  if (["new_herrnhut", "nisky", "krum_bay", "savan"].includes(estate.id)) {
    return "Moravian Archives";
  }

  if (["annas_retreat", "anna_s_retreat", "tabor", "harmoni"].includes(estate.id)) {
    return "NARA RG 55";
  }

  return "Rigsarkivet";
}

function seriesForArchive(archive, estate) {
  if (archive === "NARA RG 55") return "Mortgage, court, and survey records";
  if (archive === "Moravian Archives") return "St. Thomas estate papers";

  return estate.island === "st_john"
    ? "St. John matrikel and land-list records"
    : estate.island === "st_thomas"
      ? "St. Thomas matrikel and estate records"
      : "St. Croix matrikel and estate records";
}

function islandPrefix(island) {
  if (island === "st_thomas") return "stt";
  if (island === "st_john") return "stj";
  if (island === "st_croix") return "stx";
  return "wat";
}

const targets = colonialEstates
  .filter((estate) => estate.needs_owner_chain)
  .map((estate, index) => {
    const archive = archiveForEstate(estate);

    return {
      id: `generated-${estate.island}-${estate.id}-owner-chain`,
      estateCanonicalId: `${islandPrefix(estate.island)}_${estate.id}`,
      estateName: estate.name,
      island: estate.island,
      priority: estate.island === "st_thomas" || estate.island === "st_john" ? 2 : 3,
      status: "open",
      archive,
      recordFamily:
        archive === "NARA RG 55"
          ? "mortgage_deed_court"
          : archive === "Moravian Archives"
            ? "mission_estate_papers"
            : "matrikel",
      series: seriesForArchive(archive, estate),
      dateRange: estate.island === "st_croix" ? "1733-1917" : "1672-1917",
      searchNames: Array.from(new Set([estate.name, estate.modernEstate, ...estate.aliases])).filter(Boolean),
      extractionGoal: `Build citation-grade owner chain, aliases, quarter, acreage, boundary, and transfer evidence for ${estate.name}.`,
      expectedFields: [
        "estate name",
        "historical spelling",
        "owner",
        "year",
        "quarter",
        "acreage",
        "neighboring estates",
        "purchase/sale indicators",
        "mortgage or probate references",
        "map or survey references"
      ],
      notes: `Generated from colonialEstates canonical record ${estate.id}. Quarter: ${estate.quarter ?? "not yet verified"}.`,
    };
  });

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });

const content = `// Auto-generated by tools/historyGraph/generate-estate-archive-targets.mjs
// Rebuild with: npm run history:graph:generate-estate-targets

export const generatedEstateArchiveTargets = ${JSON.stringify(targets, null, 2)} as const;
`;

fs.writeFileSync(OUT_FILE, content);

console.log("Estate archive target generator");
console.log("================================");
console.log(`Input estates: ${colonialEstates.length}`);
console.log(`Generated targets: ${targets.length}`);
console.log("Output:", OUT_FILE);
