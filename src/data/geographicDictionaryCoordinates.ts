export function getDictionaryCoordinatesByName(name: string) {
  const key = name
    .replace(/^Estate\s+/i, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  return geographicDictionaryCoordinates.filter(
    (record) => record.normalizedName === key
  );
}
